#!/usr/bin/env python3
"""Generate the statistics in README.md from the repository model.

The block between the markers below is written by this script and nothing else:
one table of parts (branches, notes, exercises, figures) and one of courses.
Public notes only: it always builds a public model, so it never reads private/.

    python3 build/readme_stats.py           # rewrite the block in README.md
    python3 build/readme_stats.py --check   # exit 1 if the block is out of date

`make check` warns when the block is stale (rule `readme` in check.py).
Never runs git.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from model import ROOT, Repo

README = ROOT / "README.md"
START = "<!-- stats:start (generated by build/readme_stats.py; do not edit) -->"
END = "<!-- stats:end -->"
BLOCK = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)


def natural(s: str) -> list:
    """Sort key that orders 6.006 before 18.01 and CS70 before CS188."""
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def render(repo: Repo) -> str:
    """The generated block, markers included."""
    branch_part = {bid: title for title, branches in repo.parts for bid, _ in branches}
    count = {title: {"branches": len(branches), "notes": 0, "exercises": 0, "figures": 0}
             for title, branches in repo.parts}
    for n in repo.notes.values():
        if n.visibility != "public" or n.branch not in branch_part:
            continue
        c = count[branch_part[n.branch]]
        c["notes"] += 1
        c["exercises"] += len(n.problems)
        c["figures"] += sum(1 for b in n.blocks if b.startswith("fig-"))
    for rv in repo.reviews.values():   # a branch's synthesis problems (SPEC §6.3)
        if rv.visibility == "public" and rv.branch in branch_part:
            count[branch_part[rv.branch]]["exercises"] += len(rv.problems)

    cols = ("branches", "notes", "exercises", "figures")
    lines = [START, "", "| Field | Part | Branches | Notes | Exercises | Figures |",
             "|---|---|--:|--:|--:|--:|"]
    for fld, titles in repo.fields:
        for k, title in enumerate(titles):
            c = count[title]
            lines.append(f"| {fld if k == 0 else ''} | {title} | "
                         + " | ".join(str(c[x]) for x in cols) + " |")
    total = {x: sum(c[x] for c in count.values()) for x in cols}
    lines.append("| **Total** | | " + " | ".join(f"**{total[x]}**" for x in cols) + " |")

    courses = sorted((c for c in repo.courses if c.visibility == "public"),
                     key=lambda c: (c.institution.lower(), natural(c.code)))
    lines += ["", f"{len(courses)} courses are mapped onto the topic tree:", "",
              "| Course | Title | Institution |", "|---|---|---|"]
    for course in courses:
        lines.append(f"| {course.code} | {course.name} | {course.institution} |")
    lines += ["", END]
    return "\n".join(lines)


def updated(text: str, block: str) -> str | None:
    """README text with the block replaced, or None if it has no markers."""
    if not BLOCK.search(text):
        return None
    return BLOCK.sub(lambda _: block, text, count=1)


def stale(repo: Repo, path: Path = README) -> bool | None:
    """True if the README block is out of date, None if there is no block."""
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    new = updated(text, render(repo))
    return None if new is None else new != text


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Generate the statistics block in README.md.")
    ap.add_argument("--check", action="store_true", help="exit 1 if the block is out of date")
    a = ap.parse_args(argv)
    if not README.exists():
        print(f"{README}: not found")
        return 2
    repo = Repo(private=False)
    text = README.read_text(encoding="utf-8")
    new = updated(text, render(repo))
    if new is None:
        print(f"README.md: no block between {START!r} and {END!r}")
        return 2
    if a.check:
        if new != text:
            print("README.md: statistics are out of date; run make readme")
            return 1
        print("README.md: statistics are up to date")
        return 0
    if new != text:
        README.write_text(new, encoding="utf-8")
        print("README.md: statistics updated")
    else:
        print("README.md: statistics already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
